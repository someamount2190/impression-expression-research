"""Recompute provenance-limited summaries for historical operational runs."""
from __future__ import annotations

import json
import statistics
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]


def read_jsonl(path: Path):
    with path.open(encoding="utf-8") as stream:
        for line_number, line in enumerate(stream, 1):
            if not line.strip():
                continue
            try:
                yield json.loads(line)
            except json.JSONDecodeError as exc:
                raise ValueError(f"{path}:{line_number}: {exc}") from exc


def audit_legacy():
    rows = list(read_jsonl(ROOT / "reports/blind_eval_traces_100.jsonl"))
    task_ids = [row.get("task_id") for row in rows]
    if len(rows) != 100 or len(set(task_ids)) != 100:
        raise ValueError("legacy trace must contain 100 unique task rows")
    result = {"rows": len(rows), "unique_task_ids": len(set(task_ids)), "arms": {}}
    for key in ("baseline_1_unmodified", "baseline_2_prompt_specialized", "baseline_3_[SYSTEM_NAME]_autonomous"):
        data = [row[key] for row in rows]
        result["arms"][key] = {
            "first_attempt_correct": sum(bool(x.get("first_attempt_correct")) for x in data),
            "schema_valid": sum(bool(x.get("schema_valid")) for x in data),
            "task_completed": sum(bool(x.get("task_completed")) for x in data),
            "error_recovered_flags": sum(bool(x.get("error_recovered")) for x in data),
            "repeated_failures": sum(int(x.get("repeated_failures", 0)) for x in data),
            "hallucinated_claims": sum(int(x.get("hallucinated_claims", 0)) for x in data),
            "mean_tokens": statistics.mean(float(x.get("tokens_consumed", 0)) for x in data),
            "mean_latency_ms": statistics.mean(float(x.get("duration_ms", 0)) for x in data),
        }
    result["provenance_limitations"] = [
        "No complete prompt/response or provider request/response records in this artifact.",
        "The [SYSTEM_NAME] arm in run_blind_evaluation_100.py does not invoke [BASE_MODEL].",
        "The [SYSTEM_NAME] arm supplies task code/content fixtures directly for coding and file tasks.",
        "The legacy error recovery percentage is invalid (88 flags / 20 non-first-correct rows = 440%).",
        "The 31.2ms runtime excludes model inference and is not comparable to baseline inference latency.",
        "Task set is generated by code; no frozen split manifest or family-level leakage controls were preserved.",
    ]
    return result


def audit_instrumented():
    rows = list(read_jsonl(ROOT / "reports/instrumented_four_way_100.jsonl"))
    arms = defaultdict(list)
    for row in rows:
        arms[row.get("config", "missing")].append(row)
    result = {"rows": len(rows), "arms": {}}
    for arm, data in sorted(arms.items()):
        result["arms"][arm] = {
            "rows": len(data),
            "verified_completion_count": sum(bool(x.get("verified_completion")) for x in data),
            "model_generated_envelopes": sum(int(x.get("model_generated_envelopes", 0)) for x in data),
            "deterministic_fallback_steps": sum(int(x.get("deterministic_fallback_steps", 0)) for x in data),
            "mean_total_wall_ms": statistics.mean(float(x.get("total_wall_ms", 0)) for x in data),
            "mean_model_request_ms": statistics.mean(float(x.get("ollama_request_ms", 0)) for x in data),
            "mean_tokens": statistics.mean(float(x.get("generated_tokens", 0)) for x in data),
        }
    result["provenance_note"] = "Separate instrumented run; use as exploratory evidence only, not mergeable with legacy run."
    return result


if __name__ == "__main__":
    print(json.dumps({"legacy": audit_legacy(), "instrumented": audit_instrumented()}, indent=2, sort_keys=True))
